public class IfElse_statement {
  public static void main(String[] args) {
    boolean isMale = false;
    String name = "Jane";
    if (isMale) {
      System.out.println("The person is male.");
    } else {
      System.out.println("The person is not male.");
    }

    System.out.println("The person is named " + name + ".");
  }
}
