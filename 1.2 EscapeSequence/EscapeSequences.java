public class EscapeSequences {
  public static void main(String[] args) {

    System.out.println("this\tis\ta\ttab\tinsertion");  

    System.out.println("this\bis\bbackspace\binsertion");

    System.out.println("this\nis\nnewline");

    System.out.println("\'inserting a single quote character\'");

    System.out.println("\"inserting a double quote characteer\"");
    
    System.out.println("\\backslash character\\");

   
  }
}
